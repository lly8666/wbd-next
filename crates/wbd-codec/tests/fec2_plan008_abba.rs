//! PLAN-008 M3/018: ONE exact-source codec-only recovery ABBA.
//! Test-only release fixture. It is ignored unless an explicitly pinned
//! GitHub Actions Linux x86_64 native-isal run requests this exact test.
//! A=accepted CODE8cc, B=optimized CODE437, order A B B A in ONE process.
//! No first-delivery, Go KDF, NIC, latency p99, or product qualification.
#![cfg(all(feature = "native-isal", target_os = "linux", target_arch = "x86_64"))]

#[path = "support/fec_v2_code8cc.rs"]
mod accepted_code8cc;
use std::alloc::{GlobalAlloc, Layout, System};
use std::hint::black_box;
use std::sync::atomic::{AtomicU64, Ordering::Relaxed};
use std::time::Instant;
use wbd_codec::fec_v2 as candidate_code437;

const ACCEPTED_SHA: &str = "8cc5b06d6832565a80b60402a5fe2e1078e9ab2e";
const CANDIDATE_SHA: &str = "b4d638abf80bb6f12e6c944565c2aa8bb4e90792";
const K: usize = 16;
const R: usize = 16;
const FRAME_LEN: usize = 1200;
const BUDGET: usize = 1240;
const MISSING: [usize; 4] = [1, 5, 10, 14];
const ITERATIONS_PER_LEG: usize = 2_000_000;
const MIN_WALL_NS: u128 = 1_000_000_000;
const MIN_CPU_TICKS: u64 = 100;

// Instrument each successful heap allocation/zeroed allocation/reallocation
// in this ONE test process. Reports requested gross bytes, NOT peak RSS,
// retained payload or literal memory-copy instruction counts.
// Safety: pass the original allocator layout and pointer to System unchanged.
struct CountingSystem;
static ALLOC_OPS: AtomicU64 = AtomicU64::new(0);
static ALLOC_BYTES: AtomicU64 = AtomicU64::new(0);
#[global_allocator]
static ALLOCATOR: CountingSystem = CountingSystem;

unsafe impl GlobalAlloc for CountingSystem {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        let p = unsafe { System.alloc(layout) };
        if !p.is_null() {
            ALLOC_OPS.fetch_add(1, Relaxed);
            ALLOC_BYTES.fetch_add(layout.size() as u64, Relaxed);
        }
        p
    }
    unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
        let p = unsafe { System.alloc_zeroed(layout) };
        if !p.is_null() {
            ALLOC_OPS.fetch_add(1, Relaxed);
            ALLOC_BYTES.fetch_add(layout.size() as u64, Relaxed);
        }
        p
    }
    unsafe fn realloc(&self, p: *mut u8, old: Layout, size: usize) -> *mut u8 {
        let next = unsafe { System.realloc(p, old, size) };
        if !next.is_null() {
            ALLOC_OPS.fetch_add(1, Relaxed);
            ALLOC_BYTES.fetch_add(size as u64, Relaxed);
        }
        next
    }
    unsafe fn dealloc(&self, p: *mut u8, layout: Layout) {
        unsafe { System.dealloc(p, layout) }
    }
}
#[derive(Clone, Copy)]
struct AllocCounts { calls: u64, requested_bytes: u64 }
impl AllocCounts {
    fn snapshot() -> Self {
        Self { calls: ALLOC_OPS.load(Relaxed), requested_bytes: ALLOC_BYTES.load(Relaxed) }
    }
    fn since(self, earlier: Self) -> Self {
        Self {
            calls: self.calls.saturating_sub(earlier.calls),
            requested_bytes: self.requested_bytes.saturating_sub(earlier.requested_bytes),
        }
    }
}

// Linux process user+system CPU ticks; use getconf CLK_TCK from the same
// runner to interpret ticks. A zero or too-short window is INCONCLUSIVE.
fn process_cpu_ticks() -> Option<u64> {
    let raw = std::fs::read_to_string("/proc/self/stat").ok()?;
    let body = raw.rsplit_once(") ")?.1;
    let fields: Vec<_> = body.split_whitespace().collect();
    Some(fields.get(11)?.parse::<u64>().ok()? + fields.get(12)?.parse::<u64>().ok()?)
}

fn frame_checksum(result: Vec<(u8, Vec<u8>)>) -> u64 {
    assert_eq!(result.len(), MISSING.len());
    let mut sum = 0u64;
    for (index, payload) in result {
        assert_eq!(payload.len(), FRAME_LEN);
        sum = sum.wrapping_add(index as u64
            + payload[0] as u64
            + payload[599] as u64
            + payload[1199] as u64);
    }
    sum
}

#[test]
#[ignore = "ONLY pinned GitHub Actions: 2M e4 recoveries x 4 same-process native ABBA legs"]
fn m3_plan008_fec2_e4_old_new_abba() {
    assert_eq!(accepted_code8cc::Profile::Strong.parity_count(K), Ok(R));
    assert_eq!(candidate_code437::Profile::Strong.parity_count(K), Ok(R));
    let frames: Vec<Vec<u8>> = (0..K).map(|i| {
        (0..FRAME_LEN).map(|j| ((i * 31 + j * 17 + 9) % 251) as u8).collect()
    }).collect();
    let source_slices = frames.iter().map(Vec::as_slice).collect::<Vec<_>>();
    let available = frames.iter().enumerate().map(|(i, bytes)|
        if MISSING.contains(&i) { None } else { Some(bytes.as_slice()) }
    ).collect::<Vec<_>>();

    // One fixed set of four parity rows, generated by the accepted source;
    // the optimized source independently reproduces byte-identical wire.
    let accepted_encoder = accepted_code8cc::Rs16::new();
    let (parity, old_encoder) = accepted_encoder.encode_owned(99, &source_slices,
        accepted_code8cc::Profile::Strong, 0, 4, BUDGET,
        accepted_code8cc::BackendChoice::Scalar).unwrap();
    assert_eq!(old_encoder, accepted_code8cc::BackendUsed::Scalar);
    let candidate_encoder = candidate_code437::Rs16::new();
    let (candidate_parity, _) = candidate_encoder.encode_owned(99, &source_slices,
        candidate_code437::Profile::Strong, 0, 4, BUDGET,
        candidate_code437::BackendChoice::Scalar).unwrap();
    assert_eq!(parity, candidate_parity, "accepted/candidate FEC2 wire changed");

    let accepted_repairs = parity.iter().map(|b|
        accepted_code8cc::parse_repair(b, BUDGET).unwrap()
    ).collect::<Vec<_>>();
    let candidate_repairs = parity.iter().map(|b|
        candidate_code437::parse_repair(b, BUDGET).unwrap()
    ).collect::<Vec<_>>();

    let mut prior_checksum = None;
    for (leg, version) in ["A", "B", "B", "A"].into_iter().enumerate() {
        // Distinct per-leg owner instances. Warm exactly one e4 decode
        // before collecting cost: compare the steady/hot cache path only.
        let mut old = accepted_code8cc::Rs16::new();
        let mut new = candidate_code437::Rs16::new();
        if version == "A" {
            let (warm, used) = old.recover_missing(99, &available,
                &accepted_repairs, BUDGET,
                accepted_code8cc::BackendChoice::RequireNative).unwrap();
            assert_eq!(used, accepted_code8cc::BackendUsed::NativeIsaL);
            for (index, data) in warm {
                assert_eq!(data, frames[index as usize]);
            }
        } else {
            let (warm, used) = new.recover_missing(99, &available,
                &candidate_repairs, BUDGET,
                candidate_code437::BackendChoice::RequireNative).unwrap();
            assert_eq!(used, candidate_code437::BackendUsed::NativeIsaL);
            for (index, data) in warm {
                assert_eq!(data, frames[index as usize]);
            }
            let cache = new.decode_cache_stats();
            assert_eq!(cache.inverses, 1);
            assert_eq!(cache.native_tables, 1);
            assert_eq!(cache.native_table_payload_bytes, K * MISSING.len() * 32);
        }

        let cpu_begin = process_cpu_ticks();
        let alloc_begin = AllocCounts::snapshot();
        let start = Instant::now();
        let mut checksum = 0u64;
        if version == "A" {
            for _ in 0..ITERATIONS_PER_LEG {
                let (result, backend) = old.recover_missing(99, &available,
                    &accepted_repairs, BUDGET,
                    accepted_code8cc::BackendChoice::RequireNative).unwrap();
                assert_eq!(backend, accepted_code8cc::BackendUsed::NativeIsaL);
                checksum = checksum.wrapping_add(frame_checksum(result));
            }
        } else {
            for _ in 0..ITERATIONS_PER_LEG {
                let (result, backend) = new.recover_missing(99, &available,
                    &candidate_repairs, BUDGET,
                    candidate_code437::BackendChoice::RequireNative).unwrap();
                assert_eq!(backend, candidate_code437::BackendUsed::NativeIsaL);
                checksum = checksum.wrapping_add(frame_checksum(result));
            }
        }
        black_box(checksum);
        let wall_ns = start.elapsed().as_nanos();
        let alloc = AllocCounts::snapshot().since(alloc_begin);
        let cpu_ticks = cpu_begin.zip(process_cpu_ticks())
            .map(|(before, after)| after.saturating_sub(before));
        let cpu_state = if wall_ns >= MIN_WALL_NS
                && cpu_ticks.is_some_and(|ticks| ticks >= MIN_CPU_TICKS)
            { "CPU_WINDOW_VALID" } else { "CPU_INCONCLUSIVE" };
        if let Some(previous) = prior_checksum {
            assert_eq!(checksum, previous, "old/new recovered output checksum differs");
        } else {
            prior_checksum = Some(checksum);
        }
        assert!(checksum > 0 && wall_ns > 0 && alloc.calls > 0);
        let (inverse_entries, native_tables, retained_payload) = if version == "B" {
            let stats = new.decode_cache_stats();
            (stats.inverses, stats.native_tables,
                stats.inverse_payload_bytes + stats.native_table_payload_bytes
                    + stats.source_workspace_capacity_bytes)
        } else { (old.cache_entries(), 0, 0) };
        println!(
            "M3_018_ABBA leg={leg} version={version} backend=NativeIsaL k={K} r={R} \
             frame_bytes={FRAME_LEN} e=4 recoveries={ITERATIONS_PER_LEG} \
             checksum={checksum} wall_ns={wall_ns} cpu_ticks={} cpu_window={cpu_state} \
             alloc_calls={} alloc_requested_bytes={} inverse_entries={inverse_entries} \
             native_tables={native_tables} reported_retained_payload_bytes={retained_payload} \
             product=OFF packet_p99=NOT_RUN first_delivery=NOT_RUN",
            cpu_ticks.map_or("UNKNOWN".into(), |n| n.to_string()),
            alloc.calls, alloc.requested_bytes
        );
    }
    println!(
        "M3_018_ABBA_DONE baseline={ACCEPTED_SHA} candidate={CANDIDATE_SHA} \
         order=ABBA scope=CODEC_ONLY native=ACTUAL_ISAL \
         overhead=COUNTED_GLOBAL_ALLOCATOR source_copy_bytes=NOT_INSTRUMENTED \
         allocations=REQUESTED_GROSS_BYTES cpu_window_requires_1s_and_100ticks \
         upstream_isal_source=PIN_EXTERNALLY product=OFF"
    );
}
